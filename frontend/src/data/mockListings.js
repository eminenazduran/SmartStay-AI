export function filterListings(listings, filters) {
  return listings.filter(item => {
    if (filters.neighbourhood && filters.neighbourhood !== 'all' && filters.neighbourhood !== 'Tümü') {
      const target = filters.neighbourhood.toLowerCase();
      const nClean = item.neighbourhoodCleansed.toLowerCase();
      const nDist = (item.districtName || '').toLowerCase();
      if (!nClean.includes(target) && !nDist.includes(target) && !target.includes(nClean) && !target.includes(nDist)) {
        return false;
      }
    }

    if (filters.roomType && filters.roomType !== 'all') {
      const rtTarget = filters.roomType.toLowerCase();
      const rtClean = item.roomType.toLowerCase();
      if (rtTarget !== rtClean && !rtClean.includes(rtTarget) && !rtTarget.includes(rtClean)) {
        return false;
      }
    }

    if (filters.minPrice && item.price < filters.minPrice) return false;
    if (filters.maxPrice && item.price > filters.maxPrice) return false;
    if (filters.accommodates && item.accommodates < filters.accommodates) return false;

    if (filters.amenities && filters.amenities.length > 0) {
      const hasAll = filters.amenities.every(a =>
        item.amenities?.some(ia => ia.toLowerCase().includes(a.toLowerCase()))
      );
      if (!hasAll) return false;
    }

    return true;
  });
}
